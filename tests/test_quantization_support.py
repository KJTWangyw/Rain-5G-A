"""Synthetic regressions for the production OpenMRG analysis entry point.

The data loader is replaced with three constructed minutes. No field data or
published experiment outputs are used or regenerated by these tests.
"""

import contextlib
import importlib.util
import io
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest import mock

import numpy as np
import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]
ANALYSIS_PATH = PROJECT_ROOT / "experiments" / "budget" / "analyze_openmrg.py"
SPEC = importlib.util.spec_from_file_location("budget_support_analysis", ANALYSIS_PATH)
analysis = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(analysis)


class QuantizationSupportTests(unittest.TestCase):
    def run_analysis(self, tsl, rsl, quantized_rsl=None):
        """Run main with one synthetic link, two dry minutes and one wet minute."""
        rsl = np.asarray(rsl, dtype=float)
        if quantized_rsl is None:
            quantized_rsl = np.round(rsl)
        arrays = {
            "time": 1433116800 + 60 * np.arange(3),  # 2015-06-01 UTC
            "tsl": np.asarray(tsl, dtype=float)[:, None],
            "rsl": rsl[:, None],
            "rsl_var": np.zeros((3, 1)),
            "rsl_q1": np.asarray(quantized_rsl, dtype=float)[:, None],
            "offset_q1": np.zeros(1),
            "radar_min": np.array([[0.0], [0.0], [1.0]]),
        }
        metadata = pd.DataFrame([{
            "Sublink": 1, "Link": 1, "Length_km": 0.5, "Frequency_GHz": 28.0,
            "Polarization": "Vertical", "k": 0.2, "alpha": 1.0, "kL": 0.1,
        }])
        config = {
            "quantization_steps_db": [1.0],
            "wet": {"threshold_mmh": 0.1, "margin_min": 0},
            "reference": {"window_min": 2, "min_dry_min": 1},
            "event_min_minutes": 1,
            "min_wet_minutes": 1,
            "bin_min_minutes": 1,
            "hour_min_minutes": 1,
            "calibration_months": [6, 7],
            "evaluation_months": [8],
            "rain_bins_mmh": [0.0, 0.1, 2.0],
            "bootstrap": {"draws": 2, "seed": 1},
            "sensitivity": {"margin_min": [0], "window_min": [2]},
        }
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            config_path = output / "config.json"
            config_path.write_text(json.dumps(config), encoding="utf-8")
            argv = [str(ANALYSIS_PATH), "--config", str(config_path), "--out", str(output)]
            with (
                mock.patch.object(analysis, "load", return_value=(metadata, arrays)),
                mock.patch.object(analysis, "BANDS", {"synthetic": (24.0, 40.0)}),
                mock.patch.object(sys, "argv", argv),
                contextlib.redirect_stdout(io.StringIO()),
            ):
                analysis.main()
            return pd.read_csv(output / "events.csv.gz").iloc[0]

    def test_missing_tsl_uses_the_attenuation_support_for_quantization_statistics(self):
        # Including the RSL-only dry minute gives a spurious 0.65 dB increment.
        rsl = np.array([-50.4, -50.1, -50.6])
        eps = np.round(rsl) - rsl
        self.assertAlmostEqual(float(np.mean(eps[:2]) - eps[2]), 0.65)

        event = self.run_analysis([np.nan, 0.0, 0.0], rsl)
        self.assertEqual(event.n_ref, 1.0)
        self.assertAlmostEqual(event.c_ref, -50.1)
        self.assertAlmostEqual(event.eps_ref_q1, 0.1)
        self.assertAlmostEqual(event.eps_ev_q1, -0.4)
        self.assertAlmostEqual(event.att_mean, 0.5)
        self.assertAlmostEqual(event.eps_ref_q1 - event.eps_ev_q1, 0.5)

    def test_all_variants_use_common_reference_support(self):
        event = self.run_analysis(
            [0.0, 0.0, 0.0], [-50.4, -50.1, -50.6], [np.nan, -50.0, -51.0]
        )
        self.assertEqual(event.n_ref, 1.0)
        self.assertAlmostEqual(event.c_ref, -50.1)
        self.assertAlmostEqual(event.att_mean, 0.5)
        self.assertAlmostEqual(event.eps_ref_q1 - event.eps_ev_q1, 0.5)

    def test_complete_power_support_retains_both_dry_minutes(self):
        event = self.run_analysis([0.0, 0.0, 0.0], [-50.4, -50.1, -50.6])
        self.assertEqual(event.n_ref, 2.0)
        self.assertAlmostEqual(event.c_ref, -50.25)
        self.assertAlmostEqual(event.att_mean, 0.35)
        self.assertAlmostEqual(event.eps_ref_q1 - event.eps_ev_q1, 0.65)


if __name__ == "__main__":
    unittest.main()
